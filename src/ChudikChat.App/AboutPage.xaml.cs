namespace ChudikChat.App;

/// <summary>
/// Что это за программа, какой версии и кто её сделал.
/// </summary>
/// <remarks>
/// Без модели представления, в отличие от главной страницы. Показывать здесь нечего:
/// версия берётся у системы один раз при создании, остальное — постоянные,
/// наблюдать не за чем. Модель ради этого завелась бы пустой, а её ещё пришлось бы
/// регистрировать в контейнере.
/// </remarks>
public partial class AboutPage : ContentPage
{
    private const string ReleasesUrl = "https://github.com/dimaaan/chudik-chat/releases";

    public AboutPage()
    {
        InitializeComponent();

        // Версию спрашиваем у системы, а не держим своей константой: она и так уже
        // задана в csproj как ApplicationDisplayVersion, и второе место разошлось бы
        // с первым в первый же выпуск. Вдобавок сборочная автоматика дописывает
        // к ней номер прогона — в выложенной сборке это «2.0.42», — и константа
        // показывала бы не то, что человек скачал.
        //
        // Чисел показываем три — мажорная, средняя, номер сборки, — а не VersionString
        // как есть. На Windows в нём всегда четыре: MAUI берёт его из манифеста
        // пакета, где версия обязана быть четырёхчастной, и четвёртым ставит
        // ApplicationVersion из csproj — вышло бы «2.0.42.1». На своей машине номера
        // прогона нет: Windows ставит на его место ноль, а на остальных платформах
        // третьего числа нет вовсе (Build = -1). Показываем ноль везде — «2.0.0».
        //
        // Номер сборки (BuildString) отдельной строкой не показываем: автоматика
        // кладёт туда тот же номер прогона, и «Сборка 42» лишь повторяла бы хвост версии.
        var version = AppInfo.Current.Version;
        VersionLabel.Text = $"Версия {version.Major}.{version.Minor}.{Math.Max(version.Build, 0)}";
    }

    private async void OnReleasesClicked(object? sender, EventArgs e)
    {
        try
        {
            await Launcher.Default.OpenAsync(new Uri(ReleasesUrl));
        }
        catch (Exception)
        {
            // Открывать нечем или система отказала. Ругаться здесь некуда — строки
            // состояния на этом экране нет, — да и не нужно: адрес остался текстом
            // кнопки, и его видно. Тот же размен, что в MessageTextConverter.
        }
    }
}
